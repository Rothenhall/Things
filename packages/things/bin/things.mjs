function snippetFromFlags(flags, configObj, assetUrl) {
  return embedSnippet({
    src: assetUrl + '/things-chat.js',
    endpoint: flags.endpoint && flags.endpoint !== true ? flags.endpoint : undefined,
    config: configObj,
    preset: typeof flags.preset === 'string' ? flags.preset : 'mallow',
    chat: isOff(flags.chat) ? false : true,
    title: typeof flags.title === 'string' ? flags.title : undefined,
    greeting: typeof flags.greeting === 'string' ? flags.greeting : undefined,
    position: typeof flags.position === 'string' ? flags.position : undefined,
    color: typeof flags.color === 'string' ? flags.color : undefined
  });
}

function cmdInit(flags) {
  const dir = typeof flags.dir === 'string' ? flags.dir : detectAssetDir();
  const chat = !isOff(flags.chat);
  const port = String(flags.port && flags.port !== true ? flags.port : 8787);
  const endpoint = typeof flags.endpoint === 'string' ? flags.endpoint.replace(/\/+$/, '') : `http://localhost:${port}`;
  const siteUrl = typeof flags['site-url'] === 'string' ? flags['site-url'].replace(/\/+$/, '') : '';
  const origins = typeof flags.origin === 'string' ? flags.origin : (siteUrl || 'http://localhost:3000');
  const configObj = typeof flags.config === 'string' ? cleanConfig(readJson(flags.config)) : undefined;

  say(bold('Setting up Things') + dim('  (' + rel(cwd) + ')'));
  const { out, files } = copyAssets(dir);
  say(green('  copied  ') + files.map((f) => rel(path.join(out, f))).join(', '));

  const envFile = path.join(cwd, 'things.env');
  if (!exists(envFile) || flags.force) {
    fs.writeFileSync(envFile, envText({ adminToken: token(), siteUrl, origins, chat, port }));
    say(green('  created ') + 'things.env ' + dim('(contains your ADMIN_TOKEN)'));
  } else say(yellow('  kept    ') + 'things.env ' + dim('(already exists; use --force to overwrite)'));

  const contentDir = path.join(cwd, 'things-content');
  if (!exists(contentDir)) {
    fs.mkdirSync(contentDir, { recursive: true });
    fs.writeFileSync(path.join(contentDir, 'index.md'), STARTER);
    say(green('  created ') + 'things-content/index.md ' + dim('(edit this: it is what the chat answers from)'));
  } else say(yellow('  kept    ') + 'things-content/');

  if (configObj) {
    fs.writeFileSync(path.join(cwd, 'things.character.json'), JSON.stringify(configObj, null, 2) + '\n');
    say(green('  saved   ') + 'things.character.json');
  }

  const ignored = appendIgnore(['things.env', 'things-data/']);
  if (ignored.length) say(green('  ignored ') + ignored.join(', ') + dim(' in .gitignore'));

  const assetUrl = '/things';
  const snippet = snippetFromFlags({ ...flags, endpoint }, configObj, assetUrl);
  const snippetFile = path.join(cwd, 'things-snippet.html');
  if (!exists(snippetFile) || flags.force) fs.writeFileSync(snippetFile, snippet + '\n');

  say('');
  say(bold('Next'));
  say(`  1. Paste this before ${cyan('</body>')} on your pages ${dim('(also saved as things-snippet.html)')}:`);
  say('');
  say(snippet.split('\n').map((l) => '     ' + l).join('\n'));
  say('');
  if (!siteUrl) say(yellow('  2. Edit things.env and set SITE_URL and ALLOWED_ORIGINS to your real site before you go live.'));
  else say(`  2. Check ${cyan('things.env')}: ALLOWED_ORIGINS=${origins}`);
  say(`  3. Write real content in ${cyan('things-content/')} ${chat ? '(the chat answers only from it)' : '(optional in capture-only mode)'}.`);
  say(`  4. Start the collector: ${cyan('npx @rothenhall/things collector')}`);
  say(`  5. Open ${cyan('http://localhost:' + port + '/admin')} and sign in with the ADMIN_TOKEN from things.env.`);
  say(`  6. Run ${cyan('npx @rothenhall/things doctor')} to check everything.`);
  say('');
  say(dim('  Full guide: docs/GETTING_STARTED.md'));
}

function cmdSnippet(flags) {
  const configObj = typeof flags.config === 'string' ? cleanConfig(readJson(flags.config)) : undefined;
  const src = typeof flags.src === 'string' ? flags.src.replace(/\/things-chat\.js$/, '') : '/things';
  say(snippetFromFlags(flags, configObj, src));
}

function cmdUpdate(flags) {
  const dir = typeof flags.dir === 'string' ? flags.dir : detectAssetDir();
  const { out, files } = copyAssets(dir);
  say(green('Updated ') + files.map((f) => rel(path.join(out, f))).join(', '));
  say(dim('The collector code updates automatically with the package (npm update @rothenhall/things). Restart it afterwards.'));
}

function envFileFor(flags) {
  if (typeof flags.env === 'string') return path.resolve(cwd, flags.env);
  for (const f of ['things.env', '.env']) if (exists(path.join(cwd, f))) return path.join(cwd, f);
  return null;
}

function run(entry, args, env) {
  if (!exists(entry)) fail('This install is missing its collector/ folder. Reinstall @rothenhall/things.');
  const child = spawn(process.execPath, [entry, ...args], { cwd, stdio: 'inherit', env: { ...process.env, ...env } });
  const forward = (sig) => () => child.kill(sig);
  process.on('SIGINT', forward('SIGINT'));
  process.on('SIGTERM', forward('SIGTERM'));
  child.on('exit', (code, signal) => process.exit(signal ? 0 : code ?? 0));
}

function cmdCollector(flags) {
  const envFile = envFileFor(flags);
  if (!envFile) say(yellow('No things.env or .env found, so the collector will use defaults. Run `things init` first for a proper setup.'));
  else say(dim('Using settings from ' + rel(envFile)));
  const env = {};
  if (envFile) env.THINGS_ENV_FILE = envFile;
  if (flags.port && flags.port !== true) env.COLLECTOR_PORT = String(flags.port);
  run(collectorEntry, [], env);
}

function cmdImportLog(rest, flags) {
  if (!rest[0]) fail('Usage: things import-log <access.log> [--since=YYYY-MM-DD]');
  const envFile = envFileFor(flags);
  const args = [path.resolve(cwd, rest[0])];
  if (typeof flags.since === 'string') args.push('--since=' + flags.since);
  run(importEntry, args, envFile ? { THINGS_ENV_FILE: envFile } : {});
}

function parseEnv(file) {
  const out = {};
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const m = /^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/.exec(line);
    if (m && !line.trim().startsWith('#')) out[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
  return out;
}

async function cmdDoctor(flags) {
  let bad = 0, warn = 0;
  const ok = (m, note) => say(green('  OK   ') + m + (note ? dim('  ' + note) : ''));
  const no = (m, note) => { bad++; say(red('  FIX  ') + m + (note ? '  ' + note : '')); };
  const wn = (m, note) => { warn++; say(yellow('  WARN ') + m + (note ? '  ' + note : '')); };

  say(bold('Things doctor') + dim('  v' + version));
  const major = Number(process.versions.node.split('.')[0]);
  const minor = Number(process.versions.node.split('.')[1]);
  if (major > 20 || (major === 20 && minor >= 12)) ok('Node.js ' + process.versions.node);
  else no('Node.js ' + process.versions.node, 'needs 20.12 or newer');

  const dir = typeof flags.dir === 'string' ? flags.dir : detectAssetDir();
  const assets = ['things-chat.js', 'things.umd.js', 'three.min.js'].map((f) => path.join(cwd, dir, 'things', f));
  if (assets.every(exists)) ok('Widget files in ' + dir + '/things/');
  else no('Widget files missing in ' + dir + '/things/', 'run: npx @rothenhall/things init');

  const envFile = envFileFor(flags);
  let env = {};
  if (envFile) {
    ok('Settings file ' + rel(envFile));
    env = parseEnv(envFile);
  } else no('No things.env or .env', 'run: npx @rothenhall/things init');

  if (envFile) {
    if (!env.ADMIN_TOKEN) no('ADMIN_TOKEN is empty', 'the dashboard is disabled without it (npx @rothenhall/things token)');
    else if (env.ADMIN_TOKEN.length < 24) wn('ADMIN_TOKEN is short', 'use at least 24 random characters');
    else ok('ADMIN_TOKEN set');
    if (!env.SITE_URL) wn('SITE_URL is empty', 'llms.txt, sitemap and schema fall back to the request host');
    else if (!/^https?:\/\//.test(env.SITE_URL) || env.SITE_URL.endsWith('/')) wn('SITE_URL looks wrong: ' + env.SITE_URL, 'use https://example.com with no trailing slash');
    else ok('SITE_URL ' + env.SITE_URL);
    if (!env.ALLOWED_ORIGINS) wn('ALLOWED_ORIGINS is empty', 'any website can use your collector; set it before going live');
    else ok('ALLOWED_ORIGINS ' + env.ALLOWED_ORIGINS);
    const chatOn = !/^(false|0|no|off)$/i.test(env.CHAT_ENABLED || 'true');
    ok('Chat ' + (chatOn ? 'on' : 'off (capture-only)'));
    if (chatOn) {
      const cdir = path.resolve(cwd, env.CONTENT_DIR || 'content');
      let n = 0;
      if (exists(cdir)) n = fs.readdirSync(cdir).filter((f) => f.endsWith('.md') && !f.startsWith('_') && f.toLowerCase() !== 'readme.md').length;
      if (n > 0 || env.CONTENT_SITEMAP || env.CONTENT_URLS) ok(`Content: ${n} markdown file(s)` + (env.CONTENT_SITEMAP ? ' + sitemap crawl' : ''));
      else no('No content to answer from', 'add .md files to ' + (env.CONTENT_DIR || 'content') + ' or set CONTENT_SITEMAP');
      if (env.LLM_API_KEY || env.LLM_BASE_URL) ok('Answer engine: model configured');
      else wn('No LLM_API_KEY', 'the chat will quote your content instead of writing natural answers');
    }
  }

  const port = env.COLLECTOR_PORT || 8787;
  const endpoint = (typeof flags.endpoint === 'string' ? flags.endpoint : `http://localhost:${port}`).replace(/\/+$/, '');
  try {
    const r = await fetch(endpoint + '/api/health', { signal: AbortSignal.timeout(4000) });
    const j = await r.json();
    ok('Collector answers at ' + endpoint, `${j.pages} content page(s), chat ${j.chat ? 'on' : 'off'}, answers: ${j.llm}`);
    if (j.pages === 0 && j.chat) no('Collector loaded 0 content pages', 'the chat has nothing to answer from');
  } catch (e) {
    no('Collector not reachable at ' + endpoint, 'start it with: npx @rothenhall/things collector');
  }

  say('');
  if (bad) { say(red(`${bad} problem(s) to fix`) + (warn ? `, ${warn} warning(s)` : '')); process.exit(1); }
  say(warn ? yellow(`No problems, ${warn} warning(s).`) : green('Everything looks good.'));
}

// ---------------------------------------------------------------- main
const { flags, rest } = parse(process.argv.slice(2));
const cmd = rest[0];

if (flags.version || flags.v || cmd === 'version') { say(version); }
else if (!cmd || cmd === 'help' || flags.help || flags.h) help();
else if (cmd === 'init') cmdInit(flags);
else if (cmd === 'snippet') cmdSnippet(flags);
else if (cmd === 'update') cmdUpdate(flags);
else if (cmd === 'collector' || cmd === 'start') cmdCollector(flags);
else if (cmd === 'doctor') await cmdDoctor(flags);
else if (cmd === 'import-log') cmdImportLog(rest.slice(1), flags);
else if (cmd === 'token') say(token());
else { console.error(red('Unknown command: ') + cmd + '\n'); help(); process.exit(1); }
