#!/usr/bin/env node
// things: set up and run Things (a plush mascot, an optional chat, and AI-traffic analytics) for your own site.
//
//   npx @rothenhall/things init        copy the widget into your project and create a config
//   npx @rothenhall/things collector   run the collector and dashboard on this machine
//   npx @rothenhall/things doctor      check that everything is wired up
//
// Zero dependencies. Node 20.12 or newer.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { embedSnippet, version } from '../src/index.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const pkgRoot = path.resolve(here, '..');
const dist = path.join(pkgRoot, 'dist');
const collectorEntry = path.join(pkgRoot, 'collector', 'server', 'collector.mjs');
const importEntry = path.join(pkgRoot, 'collector', 'server', 'import-access-log.mjs');
const cwd = process.cwd();

const tty = process.stdout.isTTY && !process.env.NO_COLOR;
const paint = (n) => (s) => (tty ? `\x1b[${n}m${s}\x1b[0m` : String(s));
const bold = paint(1), dim = paint(2), green = paint(32), red = paint(31), yellow = paint(33), cyan = paint(36);
const say = (s = '') => console.log(s);
const fail = (msg, code = 1) => { console.error(red('Error: ') + msg); process.exit(code); };

// ---------------------------------------------------------------- args
function parse(argv) {
  const flags = {}, rest = [];
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a.startsWith('--')) {
      const eq = a.indexOf('=');
      if (eq > -1) { flags[a.slice(2, eq)] = a.slice(eq + 1); continue; }
      const key = a.slice(2);
      if (key.startsWith('no-')) { flags[key.slice(3)] = false; continue; }
      const next = argv[i + 1];
      if (next !== undefined && !next.startsWith('--')) { flags[key] = next; i++; } else flags[key] = true;
    } else rest.push(a);
  }
  return { flags, rest };
}
const isOff = (v) => v === false || /^(false|0|no|off)$/i.test(String(v));

// ---------------------------------------------------------------- files
const exists = (p) => { try { fs.accessSync(p); return true; } catch { return false; } };
const rel = (p) => path.relative(cwd, p) || '.';
const token = () => crypto.randomBytes(24).toString('hex');

function detectAssetDir() {
  for (const d of ['public', 'static', 'www', 'web']) if (exists(path.join(cwd, d)) && fs.statSync(path.join(cwd, d)).isDirectory()) return d;
  return 'public';
}

function copyAssets(dir) {
  if (!exists(dist)) fail('This install is missing its dist/ folder. Reinstall @rothenhall/things.');
  const out = path.join(cwd, dir, 'things');
  fs.mkdirSync(out, { recursive: true });
  const files = ['things-chat.js', 'things.umd.js', 'three.min.js'];
  for (const f of files) fs.copyFileSync(path.join(dist, f), path.join(out, f));
  return { out, files };
}

function appendIgnore(lines) {
  const f = path.join(cwd, '.gitignore');
  const cur = exists(f) ? fs.readFileSync(f, 'utf8') : '';
  const have = new Set(cur.split(/\r?\n/).map((l) => l.trim()));
  const add = lines.filter((l) => !have.has(l));
  if (!add.length) return [];
  fs.writeFileSync(f, cur + (cur && !cur.endsWith('\n') ? '\n' : '') + (cur ? '\n' : '') + '# Things (secrets and logs stay out of git)\n' + add.join('\n') + '\n');
  return add;
}

function readJson(file) {
  try { return JSON.parse(fs.readFileSync(path.resolve(cwd, file), 'utf8')); }
  catch (e) { fail(`Could not read ${file} as JSON: ${e.message}`); }
}
// A studio export has the engine version as "things"; strip it so only character settings remain.
const cleanConfig = (c) => { const o = { ...c }; delete o.things; return o; };

function envText(o) {
  return `# Things collector settings. Generated by \`things init\`. This file holds a secret: keep it out of git.
# Every setting is documented in docs/CONFIG_REFERENCE.md and in .env.example in the Things repo.

# Open the dashboard at http://localhost:${o.port}/admin and sign in with this token.
ADMIN_TOKEN=${o.adminToken}

# Your public site, no trailing slash.
SITE_URL=${o.siteUrl}

# Websites allowed to talk to the collector from a browser. Comma separated.
ALLOWED_ORIGINS=${o.origins}

# true = visitors can ask the character questions. false = capture-only (decoration + tracking).
CHAT_ENABLED=${o.chat ? 'true' : 'false'}

# What the chat answers from: markdown files in this folder, and/or a crawl of your site.
CONTENT_DIR=things-content
CONTENT_SITEMAP=

# Where questions, crawler hits and AI-referred visits are stored (JSONL files). Back it up by copying the folder.
DATA_DIR=things-data

# Natural-language answers (optional). Leave empty to quote your content with no model and no cost.
# OpenAI:        LLM_API_KEY=sk-...        LLM_MODEL=gpt-4o-mini
# Anthropic:     LLM_PROVIDER=anthropic    LLM_API_KEY=sk-ant-...
# Local Ollama:  LLM_BASE_URL=http://localhost:11434/v1   LLM_MODEL=llama3.2
LLM_PROVIDER=
LLM_API_KEY=
LLM_BASE_URL=
LLM_MODEL=

# Limits.
CHAT_RATE_LIMIT=20
CHAT_DAILY_LLM_LIMIT=500

COLLECTOR_PORT=${o.port}
`;
}

